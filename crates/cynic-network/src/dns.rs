//! Pure DNS Synthesis & Rendering Domain for CYNIC service Zone
//! Clean-room extracted from cynic-node to cynic-network per Foundation §481 (SoC).
//! Pure string & configuration generators. Zero I/O, zero network or filesystem calls.

pub const DEFAULT_DNS_ZONE: &str = "service.cynic";
/// Legacy compat zone, kept while pre-migration callers exist
/// (forge remote, baked search domains). Transitional: remove when the
/// last `service.cynic` reference leaves the registry and call sites.
pub const COMPAT_DNS_ZONE: &str = "synapse.cynic";
pub const SERVICE_DNS_HOSTS_FILENAME: &str = "service.hosts";
pub const COMPAT_DNS_HOSTS_FILENAME: &str = "synapse.hosts";
pub const SERVICE_DNS_COREFILE_FILENAME: &str = "Corefile";
pub const SERVICE_DNS_SERVICE_FILENAME: &str = "coredns-synapse.service";
pub const SERVICE_DNS_RESOLVED_DROPIN_FILENAME: &str = "cynic-synapse-dns.conf";
pub const SERVICE_DNS_MANIFEST_FILENAME: &str = "manifest.json";
pub const SERVICE_DNS_README_FILENAME: &str = "README.activation.md";

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DnsHostRecord {
    pub ip: String,
    pub fqdn: String,
    pub aliases: Vec<String>,
}

/// Bundle hosts filename for a zone: canonical file for the service
/// zone, compat file for the legacy zone, canonical otherwise.
pub fn hosts_filename_for_zone(zone: &str) -> &'static str {
    if zone == COMPAT_DNS_ZONE {
        COMPAT_DNS_HOSTS_FILENAME
    } else {
        SERVICE_DNS_HOSTS_FILENAME
    }
}

/// Map record names onto the compat zone: FQDNs under the canonical zone
/// move to the compat suffix, zone-less short names pass through shared.
pub fn map_names_to_compat_zone(names: &[String], canonical_zone: &str) -> Vec<String> {
    let suffix = format!(".{canonical_zone}");
    names
        .iter()
        .map(|name| {
            if let Some(bare) = name.strip_suffix(&suffix) {
                format!("{bare}.{COMPAT_DNS_ZONE}")
            } else {
                name.clone()
            }
        })
        .collect()
}

/// Renders a pure /etc/hosts or CoreDNS hosts file syntax.
pub fn render_service_hosts(records: &[DnsHostRecord]) -> String {
    let mut lines = Vec::new();
    lines.push("# Autogenerated by cynic-network for Service DNS".to_string());
    lines.push("127.0.0.1 localhost".to_string());
    lines.push("::1 localhost ip6-localhost ip6-loopback".to_string());

    for r in records {
        if r.aliases.is_empty() {
            lines.push(format!("{} {}", r.ip, r.fqdn));
        } else {
            lines.push(format!("{} {} {}", r.ip, r.fqdn, r.aliases.join(" ")));
        }
    }
    lines.push(String::new());
    lines.join("\n")
}

/// Renders a pure Corefile for CoreDNS serving the internal zone.
pub fn render_corefile(zone: &str, listen_port: u16, hosts_file_path: &str) -> String {
    format!(
        r#"{zone}:{listen_port} {{
    hosts {hosts_file_path} {{
        fallthrough
    }}
    errors
    log
    reload 10s
    cache 30
}}
"#
    )
}

/// Renders systemd-resolved drop-in configuration.
pub fn render_systemd_resolved_dropin(zone: &str, dns_ip: &str, dns_port: u16) -> String {
    format!(
        r#"[Resolve]
DNS={dns_ip}:{dns_port}
Domains=~{zone}
"#
    )
}

/// List of filenames bundled in a canonical Service DNS distribution.
pub fn canonical_dns_bundle_files() -> Vec<&'static str> {
    vec![
        SERVICE_DNS_HOSTS_FILENAME,
        COMPAT_DNS_HOSTS_FILENAME,
        SERVICE_DNS_COREFILE_FILENAME,
        SERVICE_DNS_SERVICE_FILENAME,
        SERVICE_DNS_RESOLVED_DROPIN_FILENAME,
        SERVICE_DNS_MANIFEST_FILENAME,
        SERVICE_DNS_README_FILENAME,
    ]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_hosts_file_correctly() {
        let records = vec![
            DnsHostRecord {
                ip: "10.10.10.119".to_string(),
                fqdn: "cynic-builder.service.cynic".to_string(),
                aliases: vec!["builder".to_string()],
            },
            DnsHostRecord {
                ip: "10.10.10.100".to_string(),
                fqdn: "kernel.service.cynic".to_string(),
                aliases: vec![],
            },
        ];

        let hosts = render_service_hosts(&records);
        assert!(hosts.contains("10.10.10.119 cynic-builder.service.cynic builder"));
        assert!(hosts.contains("10.10.10.100 kernel.service.cynic"));
    }

    #[test]
    fn renders_corefile_syntax() {
        let corefile = render_corefile(
            "service.cynic",
            5353,
            &format!("/etc/coredns/{SERVICE_DNS_HOSTS_FILENAME}"),
        );
        assert!(corefile.contains("service.cynic:5353 {"));
        assert!(corefile.contains(&format!("hosts /etc/coredns/{SERVICE_DNS_HOSTS_FILENAME}")));
    }

    #[test]
    fn canonical_bundle_file_list_is_stable() {
        let files = canonical_dns_bundle_files();
        assert_eq!(files.len(), 7);
        assert!(files.contains(&"Corefile"));
        assert!(files.contains(&SERVICE_DNS_HOSTS_FILENAME));
        assert!(files.contains(&COMPAT_DNS_HOSTS_FILENAME));
    }

    #[test]
    fn compat_mapping_moves_fqdn_suffix_and_keeps_shorts() {
        let mapped = map_names_to_compat_zone(
            &[
                "forgejo".to_string(),
                "forgejo.service.cynic".to_string(),
                "other.example".to_string(),
            ],
            "service.cynic",
        );
        assert_eq!(
            mapped,
            vec![
                "forgejo".to_string(),
                "forgejo.synapse.cynic".to_string(),
                "other.example".to_string(),
            ]
        );
    }

    #[test]
    fn hosts_filename_follows_zone() {
        assert_eq!(
            hosts_filename_for_zone("service.cynic"),
            SERVICE_DNS_HOSTS_FILENAME
        );
        assert_eq!(
            hosts_filename_for_zone("synapse.cynic"),
            COMPAT_DNS_HOSTS_FILENAME
        );
        assert_eq!(
            hosts_filename_for_zone("labmesh"),
            SERVICE_DNS_HOSTS_FILENAME
        );
    }
}
