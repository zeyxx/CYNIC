use std::collections::BTreeMap;
use std::error::Error;

use cynic_types::paths::CynicPaths;

use crate::dns_contract::{
    default_dns_zone, service_dns_corefile_path, service_dns_hosts_path,
    service_dns_resolved_dropin_path,
};
use crate::ports::network_interfaces_port::{
    DnsActivationPlan, DnsBundleRendererPort, RegistryNodeRecord,
};

#[derive(Debug, Clone)]
pub struct ServiceDnsRenderer {
    zone: String,
}

impl Default for ServiceDnsRenderer {
    fn default() -> Self {
        Self {
            zone: default_dns_zone(),
        }
    }
}

impl ServiceDnsRenderer {
    pub fn new(zone: impl Into<String>) -> Self {
        Self { zone: zone.into() }
    }
}

impl DnsBundleRendererPort for ServiceDnsRenderer {
    fn activation_plan(&self) -> Result<DnsActivationPlan, Box<dyn Error>> {
        Ok(DnsActivationPlan {
            zone: self.zone.clone(),
            hosts_path: service_dns_hosts_path(),
            corefile_path: service_dns_corefile_path(),
            resolved_dropin_path: service_dns_resolved_dropin_path(),
        })
    }

    fn render_hosts(&self, topology: &[RegistryNodeRecord]) -> Result<String, Box<dyn Error>> {
        let mut ip_to_names: BTreeMap<String, Vec<String>> = BTreeMap::new();
        for record in topology {
            if record.ip.trim().is_empty() {
                continue;
            }
            let entry = ip_to_names.entry(record.ip.clone()).or_default();
            for name in &record.names {
                if !name.trim().is_empty() && !entry.contains(name) {
                    entry.push(name.clone());
                }
            }
            if !entry.contains(&record.node) && !record.node.trim().is_empty() {
                entry.push(record.node.clone());
            }
        }

        let mut lines = vec![
            "# AUTO-GENERATED BY CYNIC-NODE NETWORK SURFACE".to_string(),
            format!(
                "# Source of Truth: {}",
                CynicPaths::registry_path().display()
            ),
            "# Do not edit manually.".to_string(),
            String::new(),
        ];
        for (ip, mut names) in ip_to_names {
            names.sort();
            lines.push(format!("{ip}\t{}", names.join(" ")));
        }
        Ok(lines.join("\n") + "\n")
    }

    fn render_corefile(&self) -> Result<String, Box<dyn Error>> {
        let hosts_path = service_dns_hosts_path();
        Ok(format!(
            ".:1053 {{\n    errors\n    hosts {hosts_path} {{\n        fallthrough\n    }}\n}}\n"
        ))
    }

    fn render_resolved_dropin(&self) -> Result<String, Box<dyn Error>> {
        Ok(format!(
            "[Resolve]\nDNS=127.0.0.1:1053\nDomains=~{}\n",
            self.zone
        ))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_hosts_grouped_by_ip() {
        let renderer = ServiceDnsRenderer::new("test.zone");
        let payload = renderer
            .render_hosts(&[
                RegistryNodeRecord {
                    node: "builder".to_string(),
                    ip: "10.20.0.5".to_string(),
                    names: vec![
                        "builder.service.cynic".to_string(),
                        "builder-ssh.service.cynic".to_string(),
                    ],
                },
                RegistryNodeRecord {
                    node: "build-runner".to_string(),
                    ip: "10.20.0.5".to_string(),
                    names: vec!["build-runner.service.cynic".to_string()],
                },
            ])
            .expect("render hosts");

        assert!(payload.contains("10.20.0.5"));
        assert!(payload.contains("builder.service.cynic"));
        assert!(payload.contains("builder-ssh.service.cynic"));
        assert!(payload.contains("build-runner.service.cynic"));
        assert!(payload.contains("builder"));
        assert!(payload.contains("build-runner"));
    }

    #[test]
    fn renders_compat_hosts_with_legacy_suffix() {
        use cynic_network::dns::map_names_to_compat_zone;

        let renderer = ServiceDnsRenderer::new("service.cynic");
        let topology = vec![crate::ports::network_interfaces_port::RegistryNodeRecord {
            node: "forgejo".to_string(),
            ip: "10.10.10.101".to_string(),
            names: vec!["forgejo".to_string(), "forgejo.service.cynic".to_string()],
        }];
        let compat: Vec<_> = topology
            .iter()
            .map(
                |record| crate::ports::network_interfaces_port::RegistryNodeRecord {
                    node: record.node.clone(),
                    ip: record.ip.clone(),
                    names: map_names_to_compat_zone(&record.names, "service.cynic"),
                },
            )
            .collect();
        let payload = renderer.render_hosts(&compat).expect("render compat");
        assert!(payload.contains("forgejo.synapse.cynic"));
        assert!(!payload.contains("service.cynic"));
        assert!(payload.contains("forgejo"));
    }

    #[test]
    fn renders_canonical_plan_and_templates() {
        let renderer = ServiceDnsRenderer::new("test.zone");
        let plan = renderer.activation_plan().expect("plan");
        let corefile = renderer.render_corefile().expect("corefile");
        let dropin = renderer.render_resolved_dropin().expect("dropin");

        assert_eq!(plan.zone, "test.zone");
        assert_eq!(plan.hosts_path, service_dns_hosts_path());
        assert!(corefile.contains(&service_dns_hosts_path()));
        assert!(dropin.contains("Domains=~test.zone"));
    }
}
