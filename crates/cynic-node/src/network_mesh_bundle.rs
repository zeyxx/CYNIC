use std::fs;
use std::path::Path;

use cynic_protocol::{NetworkMeshPeer, NetworkMeshPlan};
use serde::Serialize;

use crate::network_mesh_plan::build_network_mesh_plan;

const MANIFEST_FILENAME: &str = "manifest.json";
const PLAN_FILENAME: &str = "mesh-plan.json";
const README_FILENAME: &str = "README.activation.md";
const WIREGUARD_DIR: &str = "wireguard";
const DNS_FILENAME: &str = "dns-records.json";
const ACL_FILENAME: &str = "acl.json";
const ROUTES_FILENAME: &str = "routes.json";

#[derive(Debug, Clone, Serialize)]
pub(crate) struct NetworkMeshBundleReport {
    pub(crate) schema: &'static str,
    pub(crate) status: &'static str,
    pub(crate) mutates: bool,
    pub(crate) provider: String,
    pub(crate) registry_path: String,
    pub(crate) bundle_dir: String,
    pub(crate) desired_peer_count: usize,
    pub(crate) secret_policy: &'static str,
    pub(crate) can_apply: bool,
    pub(crate) bundle_files: Vec<String>,
    pub(crate) activation_requires: Vec<&'static str>,
}

pub(crate) fn build_network_mesh_bundle(
    registry_path: &str,
    provider_override: Option<&str>,
    output_dir: &str,
) -> Result<NetworkMeshBundleReport, String> {
    let plan = build_network_mesh_plan(registry_path, provider_override)?;
    let out = Path::new(output_dir);
    fs::create_dir_all(out).map_err(|error| {
        format!(
            "failed to create mesh bundle dir {}: {error}",
            out.display()
        )
    })?;
    write_json(out.join(PLAN_FILENAME), &plan)?;
    write_json(out.join(DNS_FILENAME), &plan.dns)?;
    write_json(out.join(ACL_FILENAME), &plan.acl)?;
    write_json(out.join(ROUTES_FILENAME), &plan.routes)?;
    let mut bundle_files = vec![
        PLAN_FILENAME.to_string(),
        DNS_FILENAME.to_string(),
        ACL_FILENAME.to_string(),
        ROUTES_FILENAME.to_string(),
    ];

    match plan.provider.as_str() {
        "wireguard" => {
            let wg_dir = out.join(WIREGUARD_DIR);
            fs::create_dir_all(&wg_dir).map_err(|error| {
                format!(
                    "failed to create wireguard bundle dir {}: {error}",
                    wg_dir.display()
                )
            })?;
            for peer in &plan.desired_peers {
                let filename = format!("{WIREGUARD_DIR}/{}.conf.tpl", peer.id);
                fs::write(out.join(&filename), wireguard_peer_template(&plan, peer))
                    .map_err(|error| format!("failed to write {filename}: {error}"))?;
                bundle_files.push(filename);
            }
        }
        provider => {
            let filename = format!("{provider}-plan.json");
            write_json(out.join(&filename), &plan)?;
            bundle_files.push(filename);
        }
    }

    fs::write(out.join(README_FILENAME), activation_readme(&plan))
        .map_err(|error| format!("failed to write {README_FILENAME}: {error}"))?;
    bundle_files.push(README_FILENAME.to_string());

    let report = NetworkMeshBundleReport {
        schema: "cynic.network_mesh_bundle.v1",
        status: if plan.desired_peer_count > 1 {
            "planned"
        } else {
            "insufficient_peers"
        },
        mutates: false,
        provider: plan.provider.clone(),
        registry_path: registry_path.to_string(),
        bundle_dir: out.to_string_lossy().to_string(),
        desired_peer_count: plan.desired_peer_count,
        secret_policy: "no private keys or live credentials are generated by mesh bundle",
        can_apply: false,
        bundle_files: bundle_files.clone(),
        activation_requires: vec![
            "operator_supplied_peer_private_keys",
            "bounded_network_actuator",
            "firewall_policy_bundle",
            "post_apply_runtime_observation",
        ],
    };
    write_json(out.join(MANIFEST_FILENAME), &report)?;
    Ok(report)
}

fn write_json(path: impl AsRef<Path>, value: &impl Serialize) -> Result<(), String> {
    let path = path.as_ref();
    let payload = serde_json::to_string_pretty(value).map_err(|error| error.to_string())?;
    fs::write(path, format!("{payload}\n"))
        .map_err(|error| format!("failed to write {}: {error}", path.display()))
}

fn wireguard_peer_template(plan: &NetworkMeshPlan, peer: &NetworkMeshPeer) -> String {
    let peer_sections = plan
        .desired_peers
        .iter()
        .filter(|candidate| candidate.id != peer.id)
        .map(|candidate| {
            format!(
                "[Peer]\n# peer_id = {}\nPublicKey = <{}_PUBLIC_KEY>\nAllowedIPs = {}/32\nEndpoint = <{}_ENDPOINT>\nPersistentKeepalive = 25\n",
                candidate.id,
                candidate.id.to_uppercase().replace('-', "_"),
                candidate.address,
                candidate.id.to_uppercase().replace('-', "_")
            )
        })
        .collect::<Vec<_>>()
        .join("\n");
    format!(
        "# Generated by cynic.network_mesh_bundle.v1\n# provider = {}\n# peer_id = {}\n# secrets are intentionally placeholders\n[Interface]\nPrivateKey = <{}_PRIVATE_KEY>\nAddress = {}/32\nDNS = {}\n\n{}\n",
        plan.provider,
        peer.id,
        peer.id.to_uppercase().replace('-', "_"),
        peer.address,
        plan.dns_zone.as_deref().unwrap_or("<DNS_ZONE>"),
        peer_sections
    )
}

fn activation_readme(plan: &NetworkMeshPlan) -> String {
    format!(
        "# CYNIC Mesh Bundle\n\nSchema: `cynic.network_mesh_bundle.v1`\n\nProvider: `{}`\n\nPeers: `{}`\n\nThis bundle is non-mutating. It contains desired mesh artifacts only.\n\nApply requires private key material, bounded network actuator installation, firewall policy, and post-apply runtime observation.\n",
        plan.provider, plan.desired_peer_count
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mesh_bundle_writes_manifest_plan_and_wireguard_templates() {
        let out = tempfile::tempdir().expect("tempdir");
        let registry_path = format!(
            "{}/../../infra/registries/lab.json",
            env!("CARGO_MANIFEST_DIR")
        );
        let report =
            build_network_mesh_bundle(&registry_path, None, out.path().to_str().expect("path"))
                .expect("bundle");
        assert_eq!(report.schema, "cynic.network_mesh_bundle.v1");
        assert!(!report.mutates);
        assert!(out.path().join(MANIFEST_FILENAME).exists());
        assert!(out.path().join(PLAN_FILENAME).exists());
        assert!(out.path().join("wireguard/lab-kernel.conf.tpl").exists());
    }
}
