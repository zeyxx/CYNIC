//! Build probe-driven launch plans and materialize runtime env + systemd drop-ins.

use std::fs;
use std::path::PathBuf;

use crate::adapters::local::engine_probe::probe_engine_plugins;
use crate::adapters::local::vault_inventory::FsLocalModelInventory;
use crate::domain::hardware_profile::HardwareProfile;
use crate::domain::runtime_plan::{ProfileOverrides, RuntimeLaunchPlan, plan_launch};
use crate::ports::local_runtime_port::{LocalModelInventoryPort, LocalRuntimeError};

#[derive(Debug)]
pub struct RuntimePlanner {
    inventory: FsLocalModelInventory,
}

impl RuntimePlanner {
    pub fn from_env() -> Self {
        Self {
            inventory: FsLocalModelInventory::from_env(),
        }
    }

    pub fn plan_for_alias(&self, alias: &str) -> Result<RuntimeLaunchPlan, LocalRuntimeError> {
        let profile = self.inventory.get_profile(alias)?;
        let size = profile
            .size_bytes
            .or_else(|| fs::metadata(&profile.model_path).ok().map(|m| m.len()));
        let hw = HardwareProfile::probe();
        let plugins = probe_engine_plugins(&hw);

        // Profile fields are optional overrides only — not frozen world model.
        let overrides = ProfileOverrides {
            host: Some(profile.host.clone()),
            port: Some(profile.port),
            // Only treat ctx as override if profile set something non-default-looking:
            // always pass profile ctx as soft override when present (>0)
            ctx_size: if profile.ctx_size > 0 {
                Some(profile.ctx_size)
            } else {
                None
            },
            // If profile has custom EXTRA_ARGS that aren't our old frozen defaults,
            // only force when CYNIC_FORCE_PROFILE_ARGS=1
            force_extra_args: if std::env::var("CYNIC_FORCE_PROFILE_ARGS").ok().as_deref()
                == Some("1")
                && !profile.extra_args.is_empty()
            {
                Some(profile.extra_args.clone())
            } else {
                None
            },
            force_threads: None,
            force_n_gpu_layers: None,
            force_memory_max: profile.memory_max.clone().filter(|_| {
                std::env::var("CYNIC_FORCE_PROFILE_MEMORY").ok().as_deref() == Some("1")
            }),
            force_cpu_quota: profile.cpu_quota.clone().filter(|_| {
                std::env::var("CYNIC_FORCE_PROFILE_CPU_QUOTA")
                    .ok()
                    .as_deref()
                    == Some("1")
            }),
        };

        // Prefer probe ctx unless operator freezes profile ctx
        let mut overrides = overrides;
        if std::env::var("CYNIC_FORCE_PROFILE_CTX").ok().as_deref() != Some("1") {
            overrides.ctx_size = None; // fully probe-driven
        }

        Ok(plan_launch(
            alias,
            &profile.model_path,
            size,
            &hw,
            &plugins,
            &overrides,
        ))
    }

    /// Write runtime env + systemd drop-in so start uses probed plan (not frozen EXTRA_ARGS).
    pub fn materialize(
        &self,
        plan: &RuntimeLaunchPlan,
    ) -> Result<MaterializeReport, LocalRuntimeError> {
        let runtime_dir = runtime_env_dir();
        fs::create_dir_all(&runtime_dir)
            .map_err(|e| LocalRuntimeError::Control(format!("create runtime env dir: {e}")))?;

        let env_path = runtime_dir.join(format!("{}.env", plan.alias));
        let env_body = format!(
            r#"# AUTO-GENERATED by cynic probe — do not hand-edit
# schema={schema}
# regenerate: cynic runtime inference-plan {alias} --json --apply
LLAMA_SERVER_BIN={bin}
LLAMA_MODEL_PATH={model}
LLAMA_HOST={host}
LLAMA_PORT={port}
LLAMA_CTX_SIZE={ctx}
LLAMA_EXTRA_ARGS={extra}
LLAMA_MEMORY_MAX={mem}
LLAMA_CPU_QUOTA={cpu}
CYNIC_MODEL_ALIAS={alias}
CYNIC_PLAN_SCHEMA={schema}
"#,
            schema = plan.schema,
            alias = plan.alias,
            bin = plan.plugins.llama_server_bin,
            model = plan.model_path,
            host = plan.host,
            port = plan.port,
            ctx = plan.ctx_size,
            extra = shell_escape_env(&plan.llama_extra_args),
            mem = plan.memory_max,
            cpu = plan.cpu_quota,
        );
        fs::write(&env_path, env_body)
            .map_err(|e| LocalRuntimeError::Control(format!("write runtime env: {e}")))?;

        // systemd drop-in: MemoryMax + CPUQuota from probe; EnvironmentFile runtime
        let drop_dir = systemd_dropin_dir(&plan.alias);
        fs::create_dir_all(&drop_dir)
            .map_err(|e| LocalRuntimeError::Control(format!("create drop-in dir: {e}")))?;
        let drop_path = drop_dir.join("50-probe.conf");
        let drop_body = format!(
            r#"[Service]
# probe-generated resource bounds (agnostic — not frozen 400%)
MemoryMax={mem}
CPUQuota={cpu}
EnvironmentFile=
EnvironmentFile=%h/.config/cynic/models/runtime/{alias}.env
"#,
            mem = plan.memory_max,
            cpu = plan.cpu_quota,
            alias = plan.alias,
        );
        fs::write(&drop_path, drop_body)
            .map_err(|e| LocalRuntimeError::Control(format!("write systemd drop-in: {e}")))?;

        Ok(MaterializeReport {
            runtime_env: env_path.display().to_string(),
            systemd_dropin: drop_path.display().to_string(),
        })
    }
}

#[derive(Debug, Clone, serde::Serialize)]
pub struct MaterializeReport {
    pub runtime_env: String,
    pub systemd_dropin: String,
}

fn runtime_env_dir() -> PathBuf {
    if let Ok(p) = std::env::var("CYNIC_MODEL_PROFILES") {
        return PathBuf::from(p).join("runtime");
    }
    let base = std::env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .unwrap_or_else(|| {
            std::env::var_os("HOME")
                .map(PathBuf::from)
                .unwrap_or_else(|| PathBuf::from("."))
                .join(".config")
        });
    base.join("cynic/models/runtime")
}

fn systemd_dropin_dir(alias: &str) -> PathBuf {
    let base = std::env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .unwrap_or_else(|| {
            std::env::var_os("HOME")
                .map(PathBuf::from)
                .unwrap_or_else(|| PathBuf::from("."))
                .join(".config")
        });
    base.join(format!("systemd/user/llama-server@{alias}.service.d"))
}

fn shell_escape_env(s: &str) -> String {
    // EnvironmentFile values: avoid raw newlines; keep spaces (systemd tolerates unquoted)
    s.replace('\n', " ").replace('\r', " ")
}
