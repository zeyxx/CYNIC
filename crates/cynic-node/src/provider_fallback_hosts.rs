use std::fs;
use std::path::Path;

use serde::Serialize;

use crate::adapters::registry::LocalRegistryAdapter;
use crate::ports::network_interfaces_port::{ProviderFallbackHostRecord, RegistryTopologyPort};

#[derive(Debug, Clone, Serialize)]
pub(crate) struct ProviderFallbackHostsReport {
    pub(crate) schema: &'static str,
    pub(crate) status: &'static str,
    canonical: bool,
    mutates_system: bool,
    registry_ref: String,
    hosts_path: String,
    record_count: usize,
    records: Vec<ProviderFallbackHostRecord>,
    warning: &'static str,
    expires_on: &'static str,
}

pub(crate) fn build_provider_fallback_hosts(
    registry: &str,
    output_dir: &str,
) -> Result<ProviderFallbackHostsReport, Box<dyn std::error::Error>> {
    let registry_adapter = LocalRegistryAdapter::new(registry);
    let records = registry_adapter.fetch_provider_fallback_records()?;
    let hosts = render_provider_fallback_hosts(&records);
    let out = Path::new(output_dir);
    fs::create_dir_all(out)?;
    let hosts_path = out.join("provider-fallback.hosts");
    fs::write(&hosts_path, hosts)?;
    let report = ProviderFallbackHostsReport {
        schema: "cynic.organ_fleet.provider_fallback_hosts.v1",
        status: if records.is_empty() {
            "empty"
        } else {
            "fallback_available"
        },
        canonical: false,
        mutates_system: false,
        registry_ref: registry.to_string(),
        hosts_path: hosts_path.to_string_lossy().to_string(),
        record_count: records.len(),
        records,
        warning: "Provider fallback DNS is temporary evidence plumbing, not the Synapse service contract.",
        expires_on: "network_mesh_status.runtime_status == mesh_active",
    };
    fs::write(
        out.join("manifest.json"),
        serde_json::to_string_pretty(&report)? + "\n",
    )?;
    Ok(report)
}

pub(crate) fn render_provider_fallback_hosts(records: &[ProviderFallbackHostRecord]) -> String {
    let mut lines = vec![
        "# TEMPORARY CYNIC PROVIDER FALLBACK HOSTS".to_string(),
        "# Generated by cynic-node from infra/registry.json network.local values.".to_string(),
        "# Not canonical. Remove when Synapse/WireGuard DNS is active.".to_string(),
        String::new(),
    ];
    for record in records {
        lines.push(format!("{}\t{}", record.ip, record.names.join(" ")));
    }
    lines.join("\n") + "\n"
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renderer_emits_sorted_lines() {
        let rendered = render_provider_fallback_hosts(&[
            ProviderFallbackHostRecord {
                node: "forge".to_string(),
                role: Some("build_runner".to_string()),
                provider_plane: "proxmox_guest".to_string(),
                ip: "10.10.10.4".to_string(),
                names: vec!["forge".to_string(), "forge.synapse.cynic".to_string()],
                canonical: false,
            },
        ]);

        assert!(rendered.contains("10.10.10.4\tforge forge.synapse.cynic"));
        assert!(rendered.contains("TEMPORARY CYNIC PROVIDER FALLBACK HOSTS"));
    }
}
