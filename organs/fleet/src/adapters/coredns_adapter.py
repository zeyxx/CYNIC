from __future__ import annotations

import os

from .network_entities import MeshNode


class CoreDNSAdapter:
    def __init__(self, state_dir: str):
        self.state_dir = state_dir
        self.hosts_file = os.path.join(self.state_dir, "synapse.hosts")

    def write_synapse_hosts(self, nodes: list[MeshNode]) -> bool:
        os.makedirs(self.state_dir, exist_ok=True)
        content = self.render_synapse_hosts(nodes)

        temp_file = self.hosts_file + ".tmp"
        with open(temp_file, "w", encoding="utf-8") as handle:
            handle.write(content)

        os.rename(temp_file, self.hosts_file)
        return True

    def render_synapse_hosts(self, nodes: list[MeshNode]) -> str:
        records = [
            {
                "node": node.name,
                "ip": node.mesh_ip,
                "names": [f"{node.name}.synapse.cynic"],
            }
            for node in nodes
            if node.mesh_ip
        ]
        return self.render_registry_records(records)

    def render_registry_records(self, records: list[dict]) -> str:
        lines = [
            "# AUTO-GENERATED BY CYNIC-NODE NETWORK SURFACE",
            "# Source of Truth: infra/registry.json",
            "# Do not edit manually.",
            "",
        ]

        ip_to_names: dict[str, set[str]] = {}
        for record in records:
            ip = record.get("ip")
            node = record.get("node")
            if not ip:
                continue
            ip_to_names.setdefault(ip, set())
            for name in record.get("names", []):
                if name:
                    ip_to_names[ip].add(name)
            if node:
                ip_to_names[ip].add(node)

        for ip in sorted(ip_to_names):
            names = ip_to_names[ip]
            names_str = " ".join(sorted(names))
            lines.append(f"{ip}\t{names_str}")

        return "\n".join(lines) + "\n"
