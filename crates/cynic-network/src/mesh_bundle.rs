//! Pure Network Mesh Bundle Generation Domain
//!
//! Clean-room extracted from cynic-node to cynic-network per Foundation §481 (SoC).
//! Pure transformation: (MeshRegistry) -> bundle files. I/O is isolated behind
//! the `MeshBundleWriterPort` port.

use crate::mesh_plan::{MeshRegistry, generate_mesh_plan};
use crate::types::NetworkMeshPlan;
use serde::Serialize;
use std::fs;
use std::path::{Path, PathBuf};

const MANIFEST_FILENAME: &str = "manifest.json";
const PLAN_FILENAME: &str = "mesh-plan.json";
const README_FILENAME: &str = "README.activation.md";
const WIREGUARD_DIR: &str = "wireguard";
const DNS_FILENAME: &str = "dns-records.json";
const ACL_FILENAME: &str = "acl.json";
const ROUTES_FILENAME: &str = "routes.json";

#[derive(Debug, Clone, Serialize)]
pub struct NetworkMeshBundleReport {
    pub schema: &'static str,
    pub status: &'static str,
    pub mutates: bool,
    pub provider: String,
    pub registry_path: String,
    pub bundle_dir: String,
    pub desired_peer_count: usize,
    pub secret_policy: &'static str,
    pub can_apply: bool,
    pub bundle_files: Vec<String>,
    pub activation_requires: Vec<&'static str>,
}

pub trait MeshBundleWriterPort {
    fn create_dir_all(&self, path: &Path) -> Result<(), String>;
    fn write_string(&self, path: &Path, contents: &str) -> Result<(), String>;
}

pub struct LocalNetworkMeshBundleWriter;

impl MeshBundleWriterPort for LocalNetworkMeshBundleWriter {
    fn create_dir_all(&self, path: &Path) -> Result<(), String> {
        fs::create_dir_all(path).map_err(|e| e.to_string())
    }
    fn write_string(&self, path: &Path, contents: &str) -> Result<(), String> {
        if let Some(parent) = path.parent() {
            let _ = fs::create_dir_all(parent);
        }
        fs::write(path, contents).map_err(|e| e.to_string())
    }
}

pub fn build_network_mesh_bundle(
    registry_path: &str,
    provider_override: Option<&str>,
    output_dir: &str,
) -> Result<NetworkMeshBundleReport, String> {
    build_network_mesh_bundle_with_writer(
        registry_path,
        provider_override,
        output_dir,
        &LocalNetworkMeshBundleWriter,
    )
}

pub fn build_network_mesh_bundle_with_writer(
    registry_path: &str,
    provider_override: Option<&str>,
    output_dir: &str,
    writer: &impl MeshBundleWriterPort,
) -> Result<NetworkMeshBundleReport, String> {
    let registry_text = fs::read_to_string(registry_path).map_err(|e| e.to_string())?;
    let registry: MeshRegistry = serde_json::from_str(&registry_text).map_err(|e| e.to_string())?;
    let plan = generate_mesh_plan(&registry, provider_override)?;
    // preserve registry path in plan? generate sets "infra/registry.json"; override to actual
    let mut plan = plan;
    plan.registry_path = registry_path.to_string();

    let out = Path::new(output_dir);
    writer.create_dir_all(out)?;
    write_json(&out.join(PLAN_FILENAME), &plan, writer)?;
    write_json(&out.join(DNS_FILENAME), &plan.dns, writer)?;
    write_json(&out.join(ACL_FILENAME), &plan.acl, writer)?;
    write_json(&out.join(ROUTES_FILENAME), &plan.routes, writer)?;
    let mut bundle_files = vec![
        PLAN_FILENAME.to_string(),
        DNS_FILENAME.to_string(),
        ACL_FILENAME.to_string(),
        ROUTES_FILENAME.to_string(),
    ];

    match plan.provider.as_str() {
        "wireguard" => {
            let wg_dir = out.join(WIREGUARD_DIR);
            writer.create_dir_all(&wg_dir)?;
            for peer in &plan.desired_peers {
                let filename = format!("{WIREGUARD_DIR}/{}.conf.tpl", peer.id);
                writer.write_string(&out.join(&filename), &wireguard_peer_template(&plan, peer))?;
                bundle_files.push(filename);
            }
        }
        provider => {
            let filename = format!("{provider}-plan.json");
            write_json(&out.join(&filename), &plan, writer)?;
            bundle_files.push(filename);
        }
    }

    writer.write_string(&out.join(README_FILENAME), &activation_readme(&plan))?;
    bundle_files.push(README_FILENAME.to_string());

    let report = NetworkMeshBundleReport {
        schema: "cynic.network_mesh_bundle.v1",
        status: if plan.desired_peer_count > 1 {
            "planned"
        } else {
            "insufficient_peers"
        },
        mutates: false,
        provider: plan.provider.clone(),
        registry_path: registry_path.to_string(),
        bundle_dir: out.to_string_lossy().to_string(),
        desired_peer_count: plan.desired_peer_count,
        secret_policy: "no private keys or live credentials are generated by mesh bundle",
        can_apply: false,
        bundle_files: bundle_files.clone(),
        activation_requires: vec![
            "operator_supplied_peer_private_keys",
            "bounded_network_actuator",
            "firewall_policy_bundle",
            "post_apply_runtime_observation",
        ],
    };
    write_json(&out.join(MANIFEST_FILENAME), &report, writer)?;
    Ok(report)
}

fn write_json(
    path: &Path,
    value: &impl Serialize,
    writer: &impl MeshBundleWriterPort,
) -> Result<(), String> {
    let payload = serde_json::to_string_pretty(value).map_err(|e| e.to_string())?;
    writer.write_string(path, &format!("{payload}\n"))
}

fn wireguard_peer_template(plan: &NetworkMeshPlan, peer: &crate::types::NetworkMeshPeer) -> String {
    let peer_sections = plan
        .desired_peers
        .iter()
        .filter(|candidate| candidate.id != peer.id)
        .map(|candidate| {
            format!(
                "[Peer]\n# peer_id = {}\nPublicKey = <{}_PUBLIC_KEY>\nAllowedIPs = {}/32\nEndpoint = <{}_ENDPOINT>\nPersistentKeepalive = 25\n",
                candidate.id,
                candidate.id.to_uppercase().replace('-', "_"),
                candidate.address,
                candidate.id.to_uppercase().replace('-', "_")
            )
        })
        .collect::<Vec<_>>()
        .join("\n");
    format!(
        "# Generated by cynic.network_mesh_bundle.v1\n# provider = {}\n# peer_id = {}\n# secrets are intentionally placeholders\n[Interface]\nPrivateKey = <{}_PRIVATE_KEY>\nAddress = {}/32\nDNS = {}\n\n{}\n",
        plan.provider,
        peer.id,
        peer.id.to_uppercase().replace('-', "_"),
        peer.address,
        plan.dns_zone.as_deref().unwrap_or("<DNS_ZONE>"),
        peer_sections
    )
}

fn activation_readme(plan: &NetworkMeshPlan) -> String {
    format!(
        "# CYNIC Mesh Bundle\n\nSchema: `cynic.network_mesh_bundle.v1`\n\nProvider: `{}`\n\nPeers: `{}`\n\nThis bundle is non-mutating. It contains desired mesh artifacts only.\n\nApply requires private key material, bounded network actuator installation, firewall policy, and post-apply runtime observation.\n",
        plan.provider, plan.desired_peer_count
    )
}
