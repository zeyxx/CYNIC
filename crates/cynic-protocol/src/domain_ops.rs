// ── DNS record vocabulary ─────────────────────────────────────────────────

/// DNS record type enumeration — provider-agnostic.
///
/// Covers the common RR types used in external DNS operations. DNSSEC types
/// (DS, RRSIG) and service records (SRV) are included because the article's
/// zone migration must decide proxy status for every record, and some types
/// (DNSSEC, MX, TXT) must never be proxied.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "UPPERCASE")]
pub enum DnsRecordType {
    A,
    AAAA,
    CNAME,
    TXT,
    MX,
    NS,
    CAA,
    SRV,
    DS,
}

/// Provider-agnostic DNS record shape.
///
/// This is the canonical record type that flows through the domain layer.
/// Adapters (Porkbun, Cloudflare) project their provider-specific record formats
/// into `DnsRecordShape` for reconciliation, and receive it back for writes.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct DnsRecordShape {
    /// Record name (FQDN), relative or absolute depending on provider.
    pub name: String,
    /// Record type (A, AAAA, CNAME, etc.).
    #[serde(rename = "type")]
    pub r#type: DnsRecordType,
    /// Raw record content / rdata value.
    pub content: String,
    /// Time-to-live in seconds.
    pub ttl: u32,
    /// Priority (MX, SRV). None for other types.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub priority: Option<u16>,
    /// Cloudflare proxy flag. `false` = DNS-only (grey cloud).
    /// `true` = proxied through Cloudflare edge (orange cloud).
    pub proxied: bool,
}

/// Diff between two DNS zones — the output of reconciliation.
///
/// Generated by `cynic-domain-ops::domain::reconcile`. The runner consumes
/// this to issue only the necessary add/remove/update API calls.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct ZoneRecordDiff {
    pub add: Vec<DnsRecordShape>,
    pub remove: Vec<DnsRecordShape>,
    pub update: Vec<DnsRecordShape>,
}

impl ZoneRecordDiff {
    pub fn is_empty(&self) -> bool {
        self.add.is_empty() && self.remove.is_empty() && self.update.is_empty()
    }

    pub fn total_changes(&self) -> usize {
        self.add.len() + self.remove.len() + self.update.len()
    }
}

// ── Proxy policy ──────────────────────────────────────────────────────────

/// Cloudflare proxy decision for a record category.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ProxyMode {
    /// Force Cloudflare proxy ON (orange cloud).
    Proxied,
    /// Force DNS-only (grey cloud).
    DnsOnly,
    /// Follow record-type rules: web records proxied, mail/text/dnssec DNS-only.
    Auto,
}

/// Proxy policy that drives record-shape transformation during zone migration.
///
/// Mirrors the article's principle: "MX, TXT, and anything else that can't be
/// proxied stays DNS-only. Web records follow whatever Cloudflare proxy policy
/// you set. Registrar-hosted NS records are ignored."
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct ProxyPolicy {
    pub web_records: ProxyMode,
    pub mail_records: ProxyMode,
    pub verification_records: ProxyMode,
    pub dnssec_records: ProxyMode,
}

impl Default for ProxyPolicy {
    fn default() -> Self {
        Self {
            web_records: ProxyMode::Proxied,
            mail_records: ProxyMode::DnsOnly,
            verification_records: ProxyMode::DnsOnly,
            dnssec_records: ProxyMode::DnsOnly,
        }
    }
}

/// Predicate: can this record type be proxied by Cloudflare?
///
/// CNAME, A, AAAA can be proxied. MX, TXT, NS, SRV, CAA, DS cannot.
/// This is a pure classification — no provider state is consulted.
pub fn is_proxiable_record_type(r#type: DnsRecordType) -> bool {
    matches!(
        r#type,
        DnsRecordType::A | DnsRecordType::AAAA | DnsRecordType::CNAME
    )
}

/// Predicate: should this record type follow `Auto` proxy rules?
///
/// Records that should NEVER be proxied regardless of policy.
pub fn is_dns_only_by_default(r#type: DnsRecordType) -> bool {
    matches!(
        r#type,
        DnsRecordType::MX
            | DnsRecordType::TXT
            | DnsRecordType::NS
            | DnsRecordType::SRV
            | DnsRecordType::CAA
            | DnsRecordType::DS
    )
}

/// Resolve a ProxyMode into an explicit proxy flag for a given record type.
///
/// Used by the domain layer when transforming records for Cloudflare ingestion.
/// `Auto` follows the record-type classification.
pub fn resolve_proxy_flag(r#type: DnsRecordType, mode: ProxyMode) -> bool {
    match mode {
        ProxyMode::Proxied => is_proxiable_record_type(r#type),
        ProxyMode::DnsOnly => false,
        ProxyMode::Auto => {
            if is_dns_only_by_default(r#type) {
                false
            } else {
                is_proxiable_record_type(r#type)
            }
        }
    }
}

// ── Domain validation ──────────────────────────────────────────────────────

/// Validate a domain name as pure, zero-I/O predicate.
///
/// Rules: non-empty, at least one dot, valid chars, labels not empty,
/// no leading/trailing hyphen, total length ≤ 253.
/// Returns the normalized lowercase domain or an error message.
pub fn validate_domain_name(input: &str) -> Result<String, String> {
    let trimmed = input.trim().to_lowercase();

    if trimmed.is_empty() {
        return Err("domain name is empty".to_string());
    }
    if trimmed.len() > 253 {
        return Err(format!(
            "domain name exceeds 253 chars (got {})",
            trimmed.len()
        ));
    }
    if !trimmed.contains('.') {
        return Err("domain name must contain at least one dot".to_string());
    }

    for label in trimmed.split('.') {
        if label.is_empty() {
            return Err("domain name contains empty label".to_string());
        }
        if label.len() > 63 {
            return Err(format!("DNS label exceeds 63 chars: {}", label));
        }
        if label.starts_with('-') || label.ends_with('-') {
            return Err(format!("DNS label starts or ends with hyphen: {}", label));
        }
        if !label.chars().all(|c| c.is_ascii_alphanumeric() || c == '-') {
            return Err(format!("DNS label contains invalid characters: {}", label));
        }
    }

    Ok(trimmed)
}

/// Extract the TLD (last label) from a validated domain name.
pub fn extract_tld(domain: &str) -> Option<&str> {
    if !domain.contains('.') {
        return None;
    }
    domain.split('.').last().filter(|s| !s.is_empty())
}

// ── Desired state model ────────────────────────────────────────────────────

/// External provider binding for a domain operation.
///
/// `provider` is the adapter name (e.g. "porkbun", "cloudflare").
/// `credential` is a structured `SecretReference` — never an inline secret.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ProviderConfig {
    pub provider: String,
    pub credential: SecretReference,
}

/// HTTP edge probe specification for post-action verification.
///
/// Mirrors the article's `curl --resolve` pattern: probe the intended edge
/// path directly, avoiding false negatives from recursive resolver cache.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct EdgeProbeSpec {
    /// FQDN to probe at the Cloudflare edge.
    pub fqdn: String,
    /// Expected HTTP status code (e.g. 200, 301).
    pub expected_status: Option<u16>,
    /// Expected redirect Location header value.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub expected_redirect: Option<String>,
    /// Whether to follow redirects automatically.
    #[serde(default)]
    pub follow_redirects: bool,
    /// Whether to preserve the full URL path in the probe.
    #[serde(default)]
    pub preserve_path: bool,
}

/// Desired state declaration for external domain operations.
///
/// This is the machine-readable runbook: the agent reads this, then executes
/// the bounded action chain. Secrets are referenced via `SecretReference`,
/// never inline.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DomainOpsDesiredState {
    pub schema: String,
    pub domain: String,
    pub registrar: ProviderConfig,
    pub dns_authority: ProviderConfig,
    pub proxy_policy: ProxyPolicy,
    /// Expected authoritative nameservers (e.g. Cloudflare's NS).
    pub expected_nameservers: Vec<String>,
    /// Edge HTTP probes to verify after migration.
    pub edge_probes: Vec<EdgeProbeSpec>,
    /// Desired DNS records to reconcile against the provider.
    /// Empty = migrate from registrar (legacy mode).
    /// Populated = desired-state is the source of truth (set records).
    #[serde(default)]
    pub zone_records: Vec<DnsRecordShape>,
}

// ── Operations & proofs ────────────────────────────────────────────────────

/// The operation type for a domain operation proof.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum DomainOperation {
    CheckAvailability,
    Register,
    UpdateNameservers,
    MigrateZone,
    VerifyDelegation,
    VerifyEdge,
}

/// Proof status verdict.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ProofStatus {
    /// Operation completed successfully and read-back confirms.
    Success,
    /// Operation could not complete (blocked by consent, availability, etc.).
    Blocked,
    /// Operation completed but read-back shows divergence.
    Violates,
}

/// Unified proof envelope — emitted for every domain operation.
///
/// `provider_read_back` carries the raw provider API response as JSON
/// so downstream auditors can verify without re-calling the provider.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DomainOperationProof {
    pub schema: String,
    pub domain: String,
    pub operation: DomainOperation,
    pub status: ProofStatus,
    /// Idempotency key: deterministic from (domain, content_hash, operation).
    pub idempotency_key: String,
    /// Unix timestamp of proof emission.
    pub timestamp_unix_s: u64,
    /// Raw provider API read-back response (never contains inline secrets).
    #[serde(default)]
    pub provider_read_back: serde_json::Value,
}

/// Domain availability result (registrar API read).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DomainAvailability {
    pub schema: String,
    pub domain: String,
    pub registrar: String,
    pub available: bool,
    pub premium: bool,
    pub price: Option<f64>,
    pub currency: Option<String>,
}

/// Registration confirmation (registrar API read-back after paid operation).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RegistrationReceipt {
    pub schema: String,
    pub domain: String,
    pub registrar: String,
    pub status: String,
    pub expiry_date: Option<String>,
    pub eap_code: Option<String>,
    pub idempotency_key: String,
}

/// Nameserver update confirmation (registrar API read-back).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct NameserverUpdateReceipt {
    pub schema: String,
    pub domain: String,
    pub registrar: String,
    /// Nameservers before the update (captured for rollback).
    pub previous_nameservers: Vec<String>,
    /// Nameservers after the update (read-back from registrar).
    pub current_nameservers: Vec<String>,
    pub idempotency_key: String,
}

/// Zone migration result (Cloudflare API read-back).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ZoneMigrationResult {
    pub schema: String,
    pub domain: String,
    pub zone_id: String,
    pub records_migrated: usize,
    pub records_skipped: Vec<SkippedRecord>,
    /// Reference to the append-only backup stored in cynic-askesis.
    pub backup_ref: Option<String>,
    pub idempotency_key: String,
}

/// A record that was intentionally skipped during migration with the reason.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SkippedRecord {
    pub name: String,
    #[serde(rename = "type")]
    pub r#type: DnsRecordType,
    pub reason: String,
}

/// Delegation verification result (authoritative NS query read-back).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DelegationProof {
    pub schema: String,
    pub domain: String,
    pub delegated: bool,
    /// NS records observed from authoritative resolver (not recursive).
    pub observed_nameservers: Vec<String>,
    pub expected_nameservers: Vec<String>,
    /// True when the sets match exactly.
    pub ns_set_matches: bool,
}

/// Edge HTTP probe result.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct EdgeProbeResult {
    pub schema: String,
    pub fqdn: String,
    pub expected_status: Option<u16>,
    pub observed_status: Option<u16>,
    pub observed_redirect: Option<String>,
    pub passed: bool,
}

// ── Convenience constructors ───────────────────────────────────────────────

/// Build a `SecretReference` from the `"env:VAR"` shorthand.
pub fn env_secret(id: &str, var: &str) -> SecretReference {
    SecretReference {
        id: id.to_string(),
        class: SecretClass::RuntimeMachineIdentity,
        provider: SecretProvider::ProcessEnvironment,
        locator: var.to_string(),
    }
}

/// Build a `SecretReference` from the `"file:/path"` shorthand.
pub fn file_secret(id: &str, path: &str) -> SecretReference {
    SecretReference {
        id: id.to_string(),
        class: SecretClass::RuntimeMachineIdentity,
        provider: SecretProvider::PrincipalOwnedFile,
        locator: path.to_string(),
    }
}

