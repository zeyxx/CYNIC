//! Dynamic Port Resolution & Firewall Policy Engine for CYNIC
//! 100% Rust-native, declarative Zero-Trust model. Zero shell scripts.
//! Derives allowed network bounds directly from declared registry services.

use serde::{Deserialize, Serialize};
use std::collections::BTreeSet;

pub const DYNAMIC_FIREWALL_POLICY_SCHEMA: &str = "cynic.network.firewall_policy.v1";

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum NetworkPlaneScope {
    LoopbackOnly,
    SynapseOnly,
    WireguardOnly,
    DirectManagementOnly,
    ClusterMesh, // Synapse + WireGuard + Management
    PublicWan,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DynamicPortBinding {
    pub service_name: String,
    pub port: u16,
    pub protocol: String, // "tcp" or "udp"
    pub allowed_scope: NetworkPlaneScope,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DynamicFirewallPolicy {
    pub schema: String,
    pub node_id: String,
    pub bindings: Vec<DynamicPortBinding>,
    pub generated_at_unix_ms: u64,
}

impl DynamicFirewallPolicy {
    /// Compiles declarative bindings into native nftables ruleset syntax in memory.
    /// No shell script generation: emits structured nftables table/chains directly.
    pub fn render_nftables_ruleset(&self) -> String {
        let mut rules = Vec::new();
        rules.push("#!/usr/sbin/nft -f".to_string());
        rules.push(format!(
            "# Autogenerated by cynic-network for {}",
            self.node_id
        ));
        rules.push("table inet cynic_filter {".to_string());
        rules.push("    chain inbound {".to_string());
        rules.push("        type filter hook input priority 0; policy drop;".to_string());
        rules.push("        ct state invalid drop comment \"cynic: drop invalid packets (anti-scan/malformed)\"".to_string());
        rules.push("        ct state established,related accept".to_string());
        rules.push("        iifname \"lo\" accept".to_string());
        rules.push("        ip protocol icmp accept".to_string());
        rules.push("        ip6 nexthdr icmpv6 accept".to_string());

        for b in &self.bindings {
            match b.allowed_scope {
                NetworkPlaneScope::LoopbackOnly => {
                    // Already covered by iifname lo
                }
                NetworkPlaneScope::SynapseOnly => {
                    rules.push(format!(
                        "        ip saddr 10.10.10.0/24 {} dport {} accept comment \"cynic: {} synapse-only\"",
                        b.protocol, b.port, b.service_name
                    ));
                }
                NetworkPlaneScope::WireguardOnly => {
                    rules.push(format!(
                        "        iifname \"wg0\" {} dport {} accept comment \"cynic: {} wireguard-only\"",
                        b.protocol, b.port, b.service_name
                    ));
                }
                NetworkPlaneScope::DirectManagementOnly => {
                    rules.push(format!(
                        "        ip saddr 192.168.100.0/24 {} dport {} accept comment \"cynic: {} management-only\"",
                        b.protocol, b.port, b.service_name
                    ));
                }
                NetworkPlaneScope::ClusterMesh => {
                    rules.push(format!(
                        "        ip saddr {{ 10.10.10.0/24, 192.168.100.0/24 }} {} dport {} accept comment \"cynic: {} cluster-synapse-mgmt\"",
                        b.protocol, b.port, b.service_name
                    ));
                    rules.push(format!(
                        "        iifname \"wg0\" {} dport {} accept comment \"cynic: {} cluster-wireguard\"",
                        b.protocol, b.port, b.service_name
                    ));
                }
                NetworkPlaneScope::PublicWan => {
                    if b.protocol == "udp" && b.port == 44196 {
                        // Hardened anti-DoS rate limiting for WireGuard WAN endpoint
                        rules.push(format!(
                            "        udp dport 44196 limit rate 50/second burst 100 packets accept comment \"cynic: {} public-wan anti-dos rate-limited\"",
                            b.service_name
                        ));
                    } else {
                        rules.push(format!(
                            "        {} dport {} accept comment \"cynic: {} public-wan\"",
                            b.protocol, b.port, b.service_name
                        ));
                    }
                }
            }
        }

        rules.push("    }".to_string());
        rules.push("}".to_string());
        rules.join("\n")
    }

    /// Extract set of authorized ports for SOC auditing
    pub fn allowed_ports_set(&self) -> BTreeSet<u16> {
        self.bindings.iter().map(|b| b.port).collect()
    }
}

/// Extract all declared service ports from a registry JSON Value.
/// If `target_node_id` is provided, filters for that node; otherwise collects cluster-wide declared ports.
pub fn extract_allowed_ports_from_registry(
    registry: &serde_json::Value,
    target_node_id: Option<&str>,
) -> Vec<u16> {
    let mut ports = BTreeSet::new();
    // Standard administration ports
    ports.insert(22);

    // Overlay WireGuard listen port if declared
    if let Some(policy) = registry.get("network_policy") {
        if let Some(_overlay) = policy.get("planes").and_then(|p| p.get("overlay")) {
            ports.insert(44196);
            ports.insert(51820);
        }
    }

    if let Some(nodes) = registry.get("nodes").and_then(|n| n.as_array()) {
        for node in nodes {
            let node_name = node.get("name").and_then(|v| v.as_str());
            let node_id = node.get("id").and_then(|v| v.as_str());
            let aliases: Vec<&str> = node
                .get("aliases")
                .and_then(|v| v.as_array())
                .map(|arr| arr.iter().filter_map(|v| v.as_str()).collect())
                .unwrap_or_default();

            let matches = match target_node_id {
                Some(target) => {
                    node_name == Some(target)
                        || node_id == Some(target)
                        || aliases.contains(&target)
                }
                None => true,
            };

            if matches {
                if let Some(services) = node.get("services").and_then(|s| s.as_array()) {
                    for svc in services {
                        if let Some(port) = svc.get("port").and_then(|p| p.as_u64()) {
                            ports.insert(port as u16);
                        }
                    }
                }
            }
        }
    }

    if ports.len() <= 3 {
        if let Some(nodes) = registry.get("nodes").and_then(|n| n.as_array()) {
            for node in nodes {
                if let Some(services) = node.get("services").and_then(|s| s.as_array()) {
                    for svc in services {
                        if let Some(port) = svc.get("port").and_then(|p| p.as_u64()) {
                            ports.insert(port as u16);
                        }
                    }
                }
            }
        }
    }

    ports.into_iter().collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_nftables_ruleset_with_hardened_security() {
        let policy = DynamicFirewallPolicy {
            schema: DYNAMIC_FIREWALL_POLICY_SCHEMA.to_string(),
            node_id: "cortex".to_string(),
            bindings: vec![
                DynamicPortBinding {
                    service_name: "cynic-kernel".to_string(),
                    port: 3030,
                    protocol: "tcp".to_string(),
                    allowed_scope: NetworkPlaneScope::SynapseOnly,
                },
                DynamicPortBinding {
                    service_name: "wireguard".to_string(),
                    port: 44196,
                    protocol: "udp".to_string(),
                    allowed_scope: NetworkPlaneScope::PublicWan,
                },
            ],
            generated_at_unix_ms: 1000,
        };

        let rules = policy.render_nftables_ruleset();
        assert!(rules.contains("ct state invalid drop"));
        assert!(rules.contains("udp dport 44196 limit rate 50/second burst 100 packets accept"));
        assert!(rules.contains("ip saddr 10.10.10.0/24 tcp dport 3030 accept"));
    }

    #[test]
    fn extracts_allowed_ports_from_registry_json() {
        let reg = serde_json::json!({
            "network_policy": {
                "planes": {
                    "overlay": { "cidr": "10.20.0.0/24" }
                }
            },
            "nodes": [
                {
                    "name": "cynic-kernel",
                    "services": [
                        { "name": "kernel", "port": 3030 }
                    ]
                },
                {
                    "name": "cynic-builder",
                    "services": [
                        { "name": "builder", "port": 9090 }
                    ]
                }
            ]
        });

        let kernel_ports = extract_allowed_ports_from_registry(&reg, Some("cynic-kernel"));
        assert!(kernel_ports.contains(&22));
        assert!(kernel_ports.contains(&3030));
        assert!(kernel_ports.contains(&44196));
        assert!(!kernel_ports.contains(&9090));

        let all_ports = extract_allowed_ports_from_registry(&reg, None);
        assert!(all_ports.contains(&3030));
        assert!(all_ports.contains(&9090));
    }
}
