//! Pure types for external domain operations (registrar, DNS delegation, zone migration).
//!
//! These types model **external** domain lifecycle operations — domain registration
//! through a registrar, DNS authority delegation to a provider (e.g. Cloudflare),
//! zone record migration, and authoritative verification. They are intentionally
//! provider-agnostic: the `DnsRecordShape` type captures the common substrate
//! (record type, name, content, TTL, proxy flag) so that any registrar/provider
//! adapter can project into and from it.
//!
//! Authority: foundation.json §32 (provider_agnostic_domain), §37 (portable_host_contract).
//! Zero I/O, zero provider-specific policy. All decision logic (record transform,
//! reconciliation, idempotency) lives in `cynic-domain-ops::domain`.

