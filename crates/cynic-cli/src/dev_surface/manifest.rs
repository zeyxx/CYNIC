use std::process::ExitCode;

use cynic_protocol::{
    DEVELOPMENT_SURFACE_MANIFEST_SCHEMA, FRAMEWORK_SPEC_SCHEMA, OUTCOME_SPEC_SCHEMA,
    RUNTIME_EXECUTION_PLAN_SCHEMA, RUNTIME_EXECUTION_SUITE_SCHEMA, RUNTIME_PROOF_BUNDLE_SCHEMA,
    RUNTIME_PROOF_SCHEMA, development_surface_manifest, framework_spec, outcome_spec,
    score_outcomes,
};

use crate::command_manifest::commands_manifest;
use crate::emit_json;

pub(crate) fn execute_surfaces(json: bool) -> ExitCode {
    if !json {
        return ExitCode::FAILURE;
    }
    emit_json(&development_surface_manifest(), false)
}

pub(crate) fn execute_outcomes(json: bool) -> ExitCode {
    if !json {
        return ExitCode::FAILURE;
    }
    emit_json(&outcome_spec(), false)
}

pub(crate) fn execute_kpi_score(json: bool) -> ExitCode {
    if !json {
        return ExitCode::FAILURE;
    }
    let spec = outcome_spec();
    let evidence = available_evidence();
    let commands = available_development_commands();
    emit_json(&score_outcomes(&spec, &evidence, &commands), false)
}

pub(crate) fn execute_framework(json: bool, markdown: bool) -> ExitCode {
    if json == markdown {
        return ExitCode::FAILURE;
    }

    let spec = framework_spec();
    if json {
        emit_json(&spec, false)
    } else {
        print!("{}", render_framework_ambition_ledger(&spec));
        ExitCode::SUCCESS
    }
}

fn render_framework_ambition_ledger(spec: &cynic_protocol::FrameworkSpec) -> String {
    let mut output = String::from(
        "<!-- generated by `cynic dev framework --markdown`; do not edit -->\n\n\
         | Ambition | Class | Runtime status | Current owner | Required proof |\n\
         |---|---|---|---|---|\n",
    );

    for ambition in &spec.ambition_translation {
        let classification = serialized_label(&ambition.classification);
        let status = serialized_label(&ambition.runtime_status);
        output.push_str(&format!(
            "| `{}` | `{}` | `{}` | {} | {} |\n",
            markdown_cell(ambition.id),
            markdown_cell(&classification),
            markdown_cell(&status),
            markdown_list_cell(&ambition.current_owner),
            markdown_list_cell(&ambition.required_proof),
        ));
    }

    output
}

fn serialized_label<T: serde::Serialize>(value: &T) -> String {
    match serde_json::to_value(value) {
        Ok(serde_json::Value::String(label)) => label,
        _ => "unknown".to_owned(),
    }
}

fn markdown_cell(value: &str) -> String {
    value.replace('|', "\\|").replace('\n', "<br>")
}

fn markdown_list_cell(values: &[&str]) -> String {
    markdown_cell(&values.join("<br>"))
}

#[cfg(test)]
mod tests {
    use super::markdown_list_cell;

    #[test]
    fn markdown_list_cell_preserves_all_items_and_escapes_tables() {
        assert_eq!(
            markdown_list_cell(&["owner|one", "owner two"]),
            "owner\\|one<br>owner two"
        );
    }
}

fn available_evidence() -> Vec<&'static str> {
    let manifest = development_surface_manifest();
    let mut evidence = vec![
        DEVELOPMENT_SURFACE_MANIFEST_SCHEMA,
        FRAMEWORK_SPEC_SCHEMA,
        OUTCOME_SPEC_SCHEMA,
        RUNTIME_EXECUTION_SUITE_SCHEMA,
        RUNTIME_EXECUTION_PLAN_SCHEMA,
        RUNTIME_PROOF_SCHEMA,
        RUNTIME_PROOF_BUNDLE_SCHEMA,
    ];
    evidence.extend(
        manifest
            .surfaces
            .iter()
            .flat_map(|surface| surface.exit_evidence.iter().copied()),
    );
    evidence
}

fn available_development_commands() -> Vec<&'static str> {
    let manifest = development_surface_manifest();
    let commands = commands_manifest();
    let mut available = commands
        .domains
        .iter()
        .flat_map(|domain| domain.commands.iter().copied())
        .collect::<Vec<_>>();
    available.extend(
        manifest
            .surfaces
            .iter()
            .flat_map(|surface| surface.canonical_commands.iter().copied()),
    );
    available
}
