import os
from typing import List
from ..core.ports import DnsConfigPort
from ..core.entities import MeshNode

class CoreDNSAdapter(DnsConfigPort):
    def __init__(self, state_dir: str):
        self.state_dir = state_dir
        self.hosts_file = os.path.join(self.state_dir, "synapse.hosts")

    def write_synapse_hosts(self, nodes: List[MeshNode]) -> bool:
        """
        Writes the DNS entries in a standard /etc/hosts format.
        CoreDNS 'hosts' plugin reads this file to serve 'synapse.cynic' requests.
        """
        os.makedirs(self.state_dir, exist_ok=True)
        content = self.render_synapse_hosts(nodes)

        # Atomic write pattern to avoid CoreDNS reading half a file
        temp_file = self.hosts_file + ".tmp"
        with open(temp_file, "w") as f:
            f.write(content)
        
        os.rename(temp_file, self.hosts_file)
        
        return True

    def render_synapse_hosts(self, nodes: List[MeshNode]) -> str:
        lines = [
            "# AUTO-GENERATED BY ORGAN-WIREGUARD CONTROL LOOP",
            "# Source of Truth: infra/registry.json",
            "# Do not edit manually.",
            ""
        ]

        ip_to_names = {}
        for node in nodes:
            if not node.mesh_ip:
                continue
            if node.mesh_ip not in ip_to_names:
                ip_to_names[node.mesh_ip] = set()

            fqdn = f"{node.name}.synapse.cynic"
            ip_to_names[node.mesh_ip].add(fqdn)
            ip_to_names[node.mesh_ip].add(node.name)

        for ip, names in ip_to_names.items():
            names_str = " ".join(sorted(names))
            lines.append(f"{ip}\t{names_str}")

        return "\n".join(lines) + "\n"
