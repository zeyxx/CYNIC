//! Pure DNS Synthesis & Rendering Domain for CYNIC Synapse Zone
//! Clean-room extracted from cynic-node to cynic-network per Foundation §481 (SoC).
//! Pure string & configuration generators. Zero I/O, zero network or filesystem calls.

pub const DEFAULT_DNS_ZONE: &str = "synapse.cynic";
pub const SYNAPSE_DNS_HOSTS_FILENAME: &str = "synapse.hosts";
pub const SYNAPSE_DNS_COREFILE_FILENAME: &str = "Corefile";
pub const SYNAPSE_DNS_SERVICE_FILENAME: &str = "coredns-synapse.service";
pub const SYNAPSE_DNS_RESOLVED_DROPIN_FILENAME: &str = "cynic-synapse-dns.conf";
pub const SYNAPSE_DNS_MANIFEST_FILENAME: &str = "manifest.json";
pub const SYNAPSE_DNS_README_FILENAME: &str = "README.activation.md";

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DnsHostRecord {
    pub ip: String,
    pub fqdn: String,
    pub aliases: Vec<String>,
}

/// Renders a pure /etc/hosts or CoreDNS hosts file syntax.
pub fn render_synapse_hosts(records: &[DnsHostRecord]) -> String {
    let mut lines = Vec::new();
    lines.push("# Autogenerated by cynic-network for Synapse DNS".to_string());
    lines.push("127.0.0.1 localhost".to_string());
    lines.push("::1 localhost ip6-localhost ip6-loopback".to_string());

    for r in records {
        if r.aliases.is_empty() {
            lines.push(format!("{} {}", r.ip, r.fqdn));
        } else {
            lines.push(format!("{} {} {}", r.ip, r.fqdn, r.aliases.join(" ")));
        }
    }
    lines.push(String::new());
    lines.join("\n")
}

/// Renders a pure Corefile for CoreDNS serving the internal zone.
pub fn render_corefile(zone: &str, listen_port: u16, hosts_file_path: &str) -> String {
    format!(
        r#"{zone}:{listen_port} {{
    hosts {hosts_file_path} {{
        fallthrough
    }}
    errors
    log
    reload 10s
    cache 30
}}
"#
    )
}

/// Renders systemd-resolved drop-in configuration.
pub fn render_systemd_resolved_dropin(zone: &str, dns_ip: &str, dns_port: u16) -> String {
    format!(
        r#"[Resolve]
DNS={dns_ip}:{dns_port}
Domains=~{zone}
"#
    )
}

/// List of filenames bundled in a canonical Synapse DNS distribution.
pub fn canonical_dns_bundle_files() -> Vec<&'static str> {
    vec![
        SYNAPSE_DNS_HOSTS_FILENAME,
        SYNAPSE_DNS_COREFILE_FILENAME,
        SYNAPSE_DNS_SERVICE_FILENAME,
        SYNAPSE_DNS_RESOLVED_DROPIN_FILENAME,
        SYNAPSE_DNS_MANIFEST_FILENAME,
        SYNAPSE_DNS_README_FILENAME,
    ]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_hosts_file_correctly() {
        let records = vec![
            DnsHostRecord {
                ip: "10.10.10.119".to_string(),
                fqdn: "cynic-builder.synapse.cynic".to_string(),
                aliases: vec!["builder".to_string()],
            },
            DnsHostRecord {
                ip: "10.10.10.100".to_string(),
                fqdn: "kernel.synapse.cynic".to_string(),
                aliases: vec![],
            },
        ];

        let hosts = render_synapse_hosts(&records);
        assert!(hosts.contains("10.10.10.119 cynic-builder.synapse.cynic builder"));
        assert!(hosts.contains("10.10.10.100 kernel.synapse.cynic"));
    }

    #[test]
    fn renders_corefile_syntax() {
        let corefile = render_corefile("synapse.cynic", 5353, "/etc/coredns/synapse.hosts");
        assert!(corefile.contains("synapse.cynic:5353 {"));
        assert!(corefile.contains("hosts /etc/coredns/synapse.hosts"));
    }

    #[test]
    fn canonical_bundle_file_list_is_stable() {
        let files = canonical_dns_bundle_files();
        assert_eq!(files.len(), 6);
        assert!(files.contains(&"Corefile"));
    }
}
